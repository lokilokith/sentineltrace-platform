def _debug_cache_state() -> dict:
    """INTERNAL USE ONLY. Returns cache metadata for debugging."""
    with _STORE_LOCK:
        return {
            "total_runs":  len(_ANALYSIS_STORE),
            "max_size":    _STORE_MAX_SIZE,
            "run_ids":     list(_ANALYSIS_STORE.keys()),
            "evict_order": list(_STORE_ORDER),
        }
