# Atomic stage priorities for monotonic progress
STAGE_ORDER = {"primary": 1, "insight": 2, "fused": 3}


def _stage_priority(stage: Optional[str]) -> int:
    if not stage:
        return 0
    return _AUTHORITATIVE_STAGE_ORDER.get(str(stage).strip().lower(), 0)

